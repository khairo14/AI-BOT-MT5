"""
Signals routes — pending signal queue management.
Signals are generated by the strategy runner and queued here
for manual confirmation (approve/reject) or auto-execution.
"""

import asyncio
import uuid
from datetime import datetime, timezone
from typing import Optional

from fastapi import APIRouter, HTTPException, Request
from pydantic import BaseModel
from slowapi import Limiter
from slowapi.util import get_remote_address

from api.signal_bus import bus

router = APIRouter()
limiter = Limiter(key_func=get_remote_address)
# Lock to prevent two simultaneous approve requests from placing duplicate orders.
# asyncio.Lock — correct for async endpoints; threading.Lock would block the event loop.
_approve_lock = asyncio.Lock()


def _sanitize_value(v):
    """Convert numpy scalar types to native Python types for JSON serialization."""
    if hasattr(v, "item"):  # numpy scalars expose .item()
        return v.item()
    if isinstance(v, dict):
        return {k2: _sanitize_value(v2) for k2, v2 in v.items()}
    return v


def _sanitize_dict(signal: dict) -> dict:
    return {k: _sanitize_value(v) for k, v in signal.items()}


def _sanitize(signals: list) -> list:
    return [_sanitize_dict(s) for s in signals]


class Signal(BaseModel):
    symbol: str
    direction: str          # "BUY" or "SELL"
    trading_mode: str       # "scalping" | "day_trading" | "swing"
    strategy: str
    entry_price: float
    sl: float
    tp: Optional[float] = None
    lot_size: Optional[float] = None
    confidence: Optional[float] = None
    timeframe: str = ""
    note: Optional[str] = None


